def client_type_id(value):
    """The ItemTypeWindow sprite ID the client can show for a stored type, else None."""
    if not isinstance(value, str):
        return None
    value = CLIENT_TYPE_MERGES.get(value, STORE_TYPE_ALIASES.get(value, value))
    return value if value in CLIENT_TYPE_SPRITES else None


def _content_rank(category):
    category = FEMALE_TYPE_SPRITES.get(category, category)
    members = [i for i, name in enumerate(CLOTH_CONTENT) if name == category or client_type_id(name) == category]
    return min(members) if members else len(CLOTH_CONTENT)


def client_type_rank(type_id):
    """Position of a client type ID in AEManager.TypeContent order."""
    return _content_rank(type_id)


def client_type_ids(stored):
    """TypeData IDs to emit: client-displayable, deduplicated, enum ordered.

    A stored type without a client sprite would crash the native category list,
    so it is omitted (and logged) instead of being sent.
    """
    result = set()
    for value in stored:
        mapped = client_type_id(value)
        if mapped is None:
            missing_data("shop_type_without_client_icon", type_id=value)
        else:
            result.add(mapped)
    return sorted(result, key=lambda t: (client_type_rank(t), t))


def table_rank(table):
    if table in HOUSING_MENU:
        return HOUSING_MENU.index(table)
    if isinstance(table, str) and table.startswith(("CLOTH_", "FCLOTH_")):
        return _content_rank(table)
    return 0


