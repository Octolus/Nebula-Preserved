def label(value):
    return (value or "").replace("CLOTH_BODY_", "").replace("CLOTH_HEAD_", "").replace("HOUSING_", "").replace("_", " ").title()


def identity(row):
    wardrobe = row["kind"] == "wardrobe"
    return (row["kind"], row["item_id"], (row.get("gender") or "") if wardrobe else "",
            (row.get("category") or "") if wardrobe else "")


def offer_id(row):
    digest = hashlib.sha256(json.dumps(identity(row), ensure_ascii=True, separators=(",", ":")).encode()).hexdigest()
    return POLICY + "-" + digest[:32]


def clean_text(value, maximum=128):
    """Wire/panel-safe single-line text, or None (``#`` is the wire separator)."""
    if not isinstance(value, str):
        return None
    value = " ".join(value.split())
    if (not value or len(value) > maximum or "#" in value
            or any(unicodedata.category(c).startswith("C") for c in value)):
        return None
    return value


def _load_identity_file(protocol_dir, name, label):
    """Generated per-identity metadata keyed by canonical identity; {} when absent.

    Parsed once per file version. A malformed file fails loudly instead of
    silently presenting another item's data.
    """
    path = Path(protocol_dir) / name
    try:
        stat = path.stat()
    except FileNotFoundError:
        return {}
    key = (str(path), stat.st_mtime_ns, stat.st_size)
    cached = _METADATA_CACHE.get(str(path))
    if cached is None or cached[0] != key:
        document = json.loads(path.read_text(encoding="utf-8"))
        if document.get("format_version") != 1 or not isinstance(document.get("items"), list):
            raise ProtocolError("Unsupported " + label + " format", 501)
        entries = {}
        for entry in document["items"]:
            if (not isinstance(entry, dict) or entry.get("kind") not in KINDS
                    or not isinstance(entry.get("item_id"), str)):
                raise ProtocolError("Invalid " + label + " entry", 501)
            if identity(entry) in entries:
                raise ProtocolError("Duplicate " + label + " identity", 501)
            entries[identity(entry)] = entry
        _METADATA_CACHE[str(path)] = cached = (key, entries)
    return cached[1]


def load_item_metadata(protocol_dir):
    """protocol/item-display-metadata.json keyed by canonical identity."""
    return _load_identity_file(protocol_dir, METADATA_FILE, "item display metadata")


def load_catalog_metadata(protocol_dir):
    """protocol/item-catalog-metadata.json (shipped component fields) by identity."""
    return _load_identity_file(protocol_dir, CATALOG_METADATA_FILE, "item catalog metadata")


def _protocol_json(protocol_dir, name):
    path = Path(protocol_dir) / name
    try:
        stat = path.stat()
    except FileNotFoundError:
        return {}
    key = (stat.st_mtime_ns, stat.st_size)
    cached = _PROTOCOL_CACHE.get(str(path))
    if cached is None or cached[0] != key:
        _PROTOCOL_CACHE[str(path)] = cached = (key, json.loads(path.read_text(encoding="utf-8")))
    return cached[1]


def display_fields(entry, fallback):
    """Best available name with explicit provenance; never invents text."""
    entry = entry or {}
    original = clean_text(entry.get("original_name"))
    derived = clean_text(entry.get("derived_name"), 80)
    if original:
        source, best = "original_shipped_string", original
    elif derived:
        source, best = "derived_asset_name", derived
    else:
        source, best = "preservation_label", None
    alternatives = [x for x in map(clean_text, entry.get("derived_name_alternatives") or []) if x]
    labels = [x for x in map(clean_text, entry.get("interaction_labels") or []) if x]
    return {"original_name": original, "description": clean_text(entry.get("description"), 1024),
            "derived_name": derived,
            "derived_name_confidence": entry.get("derived_name_confidence") if derived else None,
            "derived_name_alternatives": alternatives[:3], "season_hint": clean_text(entry.get("season_hint"), 32),
            "interaction_labels": labels[:8], "display_name": best, "name_source": source,
            "display_name_source": DISPLAY_NAME_SOURCES.get(source), "preservation_label": fallback,
            "name": best or fallback,
            "item_metadata": ({"source_file": "protocol/" + METADATA_FILE, **(entry.get("provenance") or {})}
                              if entry else None)}


def catalog_overrides(db):
    """Operator-edited fields per (entity_kind, entity_id); owned by store_management."""
    if not db.execute("SELECT 1 FROM sqlite_schema WHERE type='table' AND name='management_catalog_overrides'").fetchone():
        return {}
    return {(r["entity_kind"], r["entity_id"]): set(json.loads(r["changed_fields"]))
            for r in db.execute("SELECT * FROM management_catalog_overrides")}


def preview_fields(resource_path):
    """Opaque lookup key only; never reads a file or establishes availability.

    Item paths retain their .png suffix. Shop artwork uses its extensionless
    ResourceManager key. The private extractor follows this exact normalization;
    the server resolves only an allowlisted image index, not this resource path.
    """
    if not isinstance(resource_path, str) or not resource_path:
        return {"preview_key": None, "preview_url": None}
    normalized = resource_path.replace("\\", "/").lower()
    key = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    return {"preview_key": key, "preview_url": "/api/catalog-preview/" + key}


