def catalog_fields(kind, asset, row, meta, contract=None, interaction=None, max_space=None):
    """Category, navigation and shipped component fields for one catalog row.

    Every value is either read from a shipped enum/manifest/component (named in
    ``metadata_sources``) or explicitly marked as derived/preservation policy.
    """
    meta = meta or {}
    category, wardrobe = row["category"], kind == "wardrobe"
    type_shop = STORE_SPECS[kind][0]
    gender_id = {"MALE": 0, "FEMALE": 1}.get(row["gender"]) if wardrobe else STORE_SPECS[kind][5]
    sources = {"store_category": "client ItemTypeWindow sprite list (resources.assets path ID 16353)",
               "shop_path": "client ShopManager/GenderWindow/ItemTypeWindow flow",
               "sort_order": "client category enum order, then display name"}
    fields = {
        "gender_variant": row["gender"] if wardrobe else "unisex",
        "category_group": ("head" if category.startswith("CLOTH_HEAD_") else "body") if wardrobe else None,
        "category_enum": None, "slot_side": None,
        "store_category_label": label(row["store_category"]) if wardrobe else None,
        "shop_path": {"type_shop": type_shop, "store_type": TYPE_SHOP_NAMES[type_shop],
                      "gender_id": gender_id, "gender_tab": GENDER_TABS[gender_id],
                      "type_id": row["store_category"] if wardrobe else None,
                      "type_rank": client_type_rank(row["store_category"]) if wardrobe else 0,
                      "list": ("TypeData then ItemData" if wardrobe else "ItemData for type PERSON"
                               if kind == "personal_spaces" else "direct ItemData")},
        "subcategory": None, "subcategory_source": None,
        "heel_type": meta.get("heel_type"), "hand_type": meta.get("hand_type"),
        "component_classes": list(meta.get("component_classes") or []),
        "animator_controllers": list(meta.get("animator_controllers") or []),
        "locomotion_max_speed": (meta.get("locomotion") or {}).get("max_speed") if kind == "locomotions" else None,
        "variant_family": meta.get("variant_family"), "variant_family_size": meta.get("variant_family_size"),
        "variant_basis": meta.get("variant_basis"),
        "housing_menu_element": None, "housing_group": None, "housing_placement": None,
        "interaction_classes": [],
        "catalog_metadata": ({"source_file": "protocol/" + CATALOG_METADATA_FILE, **(meta.get("provenance") or {})}
                             if meta else None),
    }
    if wardrobe:
        if category in CLOTH_CONTENT:
            fields["category_enum"] = {"enum": "AEManager.TypeContent", "name": category,
                                       "value": CLOTH_CONTENT.index(category)}
            sources["category_enum"] = "client enum AEManager.TypeContent"
        if category.startswith(SIDED_SLOTS) and category[-1:] in SIDES:
            fields["slot_side"] = SIDES[category[-1]]
            sources["slot_side"] = "shipped category name suffix"
        if category != row["store_category"]:
            fields["subcategory"], fields["subcategory_source"] = category, "shipped_category"
        elif fields["heel_type"]:
            fields["subcategory"], fields["subcategory_source"] = fields["heel_type"], "shipped_component:HighHeel._type"
        elif fields["hand_type"]:
            fields["subcategory"], fields["subcategory_source"] = fields["hand_type"], "shipped_component:HandType._type"
    elif kind == "housing":
        if category in HOUSING_MENU:
            index = HOUSING_MENU.index(category)
            fields["housing_menu_element"] = HOUSING_MENU_NAMES[index]
            fields["category_enum"] = {"enum": "HousingUIContentManager.TypeServerElement",
                                       "name": HOUSING_MENU_NAMES[index], "value": index}
            sources["category_enum"] = "client enum HousingUIContentManager.TypeServerElement"
        fields["housing_group"] = HOUSING_GROUPS.get(category)
        sources["housing_group"] = "preservation grouping of the shipped table (derived)"
        if contract:
            component = meta.get("housing_component") or {}
            fields["housing_placement"] = {
                "behaviour": contract.get("behaviour"), "slot_kind": PLACEMENT_SLOTS.get(contract.get("behaviour")),
                "placement_cost": contract.get("placement_cost"), "serialized_size": contract.get("serialized_size"),
                "max_placement_space": max_space, "component_class": component.get("class"),
                "type_ground": component.get("type_ground"),
                "serialized_tablename": component.get("serialized_tablename"),
                "serialized_tablename_conflict": bool(component.get("serialized_tablename")
                                                      and component.get("serialized_tablename") != category),
            }
            fields["subcategory"], fields["subcategory_source"] = contract.get("behaviour"), "housing-placement-contracts.json"
            sources["housing_placement"] = "housing-placement-contracts.json + shipped HousingAsset component"
        if interaction:
            fields["interaction_classes"] = sorted({i["class"] for i in interaction.get("interactions", [])
                                                    if i.get("admission") == "allow" and i.get("class")})
            sources["interaction_classes"] = "housing-interaction-manifest.json"
    elif kind == "companions":
        special = [c for c in fields["component_classes"] if not any(h in c for h in EFFECT_CLASS_HINTS)]
